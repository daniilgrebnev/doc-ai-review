export function buildReviseUserMessage(
  document: string,
  remarks: string,
  variant: "default" | "template" | "minimal" = "default"
): string {
  if (variant === "template") {
    return `Шаблон договора:\n\n${document}\n\nПравки от сотрудников:\n${remarks}\n\nПримени правки и верни полный обновлённый текст.`;
  }

  if (variant === "minimal") {
    return `Текст:\n\n${document}\n\nПравки:\n${remarks}\n\nВерни исправленный текст целиком.`;
  }

  return `Исходный документ:\n\n${document}\n\nЗамечания экспертов:\n${remarks}\n\nВерни исправленный документ.`;
}

export function buildPatchUserMessage(document: string, remarks: string): string {
  return `Документ:\n\n${document}\n\nЗамечания экспертов:\n${remarks}\n\nВерни JSON-массив правок find/replace.`;
}
